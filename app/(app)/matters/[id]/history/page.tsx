import type { Metadata } from "next";
import { Suspense } from "react";
import { notFound } from "next/navigation";
import { getMatter } from "@/lib/matters";
import { listDocumentHistory } from "@/lib/documents/load";
import { templateName } from "@/lib/documents/registry";
import { Section } from "@/components/ui";

export const metadata: Metadata = { title: "Document history" };

type Params = Promise<{ id: string }>;

const when = new Intl.DateTimeFormat("en-SG", {
  timeZone: "Asia/Singapore", day: "numeric", month: "long", year: "numeric", hour: "numeric", minute: "2-digit",
});

export default function HistoryPage({ params }: { params: Params }) {
  return (
    <Suspense fallback={<div className="h-64 animate-pulse rounded-3xl bg-mint-soft" />}>
      <History params={params} />
    </Suspense>
  );
}

async function History({ params }: { params: Params }) {
  const { id } = await params;
  const [bundle, rows] = await Promise.all([getMatter(id), listDocumentHistory(id)]);
  if (!bundle) notFound();
  return (
    <div className="flex flex-col gap-5">
      <div>
        <p className="text-[12.5px] font-bold uppercase tracking-wider text-accent">History</p>
        <h1 className="text-[26px] text-ink">{bundle.matter.name}</h1>
      </div>
      <Section
        title="Documents generated"
        tone="mint"
        description="What was generated, when and by whom. The files themselves are never stored, only downloaded to your computer."
      >
        {rows.length === 0 ? (
          <p className="text-sm text-muted">Nothing generated yet.</p>
        ) : (
          <table className="w-full text-left text-sm">
            <thead className="text-[12px] font-bold uppercase tracking-wider text-mint">
              <tr>
                <th className="py-2">Document</th>
                <th className="py-2">Generated by</th>
                <th className="py-2">When</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-mint-soft">
              {rows.map((r) => (
                <tr key={r.id}>
                  <td className="py-2.5 font-bold text-ink">{templateName(r.template_key)}</td>
                  <td className="py-2.5 text-ink-soft">{r.generated_by_name}</td>
                  <td className="py-2.5 text-ink-soft">{when.format(new Date(r.generated_at))}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </Section>
    </div>
  );
}
